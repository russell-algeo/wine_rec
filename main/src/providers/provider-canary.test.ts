import { afterEach, describe, expect, it, vi } from "vitest";

import {
  classifyProviderCanaryBody,
  runProviderCanary,
} from "./provider-canary.js";
import { appConfig } from "../config.js";
import {
  classifyVivinoCurlExploreBody,
  searchVivinoExploreWithCurl,
} from "./vivino-explore-curl.js";
import * as vivinoExploreCurl from "./vivino-explore-curl.js";
import {
  RetryableVivinoBrowserError,
  VivinoBrowser,
  type SearchHit,
} from "./vivino-browser.js";

function candidate(id: string) {
  return {
    id,
    rawText: "Domaine Test Label 2021",
    price: null,
    menuTab: null,
    menuSection: null,
    lineNumber: 0,
    producer: "Domaine Test",
    label: "Label",
    vintage: 2021,
    color: "red",
    varietal: null,
    region: null,
    notes: null,
    extractionConfidence: 0.9,
  };
}

function searchHit(overrides: Partial<SearchHit> = {}): SearchHit {
  return {
    wineId: 123,
    wineryName: "Domaine Test",
    wineName: "Label",
    regionAndCountry: "Test Region",
    rating: 4.1,
    retailPrice: null,
    imageUrl: null,
    vintagePageUrl: "https://www.vivino.com/wines/123",
    year: 2021,
    ...overrides,
  };
}

describe("provider canary classification", () => {
  const originalTransport = appConfig.vivinoDirectSearchTransport;

  afterEach(() => {
    appConfig.vivinoDirectSearchTransport = originalTransport;
  });

  it("classifies CloudFront/WAF blocks separately from empty results", () => {
    expect(classifyProviderCanaryBody({
      statusCode: 403,
      body: "ERROR: The request could not be satisfied. Generated by cloudfront",
    })).toBe("cloudfront-waf");

    expect(classifyProviderCanaryBody({
      statusCode: 200,
      body: "No wines found for this search",
      recordCount: 0,
    })).toBe("zero-results");
  });

  it("classifies successful provider bodies by status and record count", () => {
    expect(classifyProviderCanaryBody({
      statusCode: 200,
      body: "<html></html>",
      recordCount: 4,
    })).toBe("ok");
  });

  it("classifies cURL Explore WAF responses", () => {
    expect(classifyVivinoCurlExploreBody({
      statusCode: 403,
      body: "ERROR: The request could not be satisfied. Generated by cloudfront",
    })).toBe("cloudfront-waf");

    expect(classifyVivinoCurlExploreBody({
      statusCode: 200,
      body: "{\"explore_vintage\":{\"matches\":[]}}",
    })).toBe("ok");
  });
});

describe("runProviderCanary", () => {
  const originalTransport = appConfig.vivinoDirectSearchTransport;

  afterEach(() => {
    vi.restoreAllMocks();
    appConfig.vivinoDirectSearchTransport = originalTransport;
    delete process.env.WINE_REC_PROVIDER_CANARY_COOLDOWN_MS;
  });

  it("keeps dry runs local and separate from recommendation quality", async () => {
    const result = await runProviderCanary({
      mode: "dry-run",
      candidates: [candidate("candidate-1")],
    });

    expect(result).toEqual(expect.objectContaining({
      provider: "vivino-direct",
      mode: "dry-run",
      candidateLimit: 5,
      recommendationQualityEvaluated: false,
      safety: {
        execution: "serial",
        cooldownMs: 0,
        stopOnFirstBlockOrError: true,
      },
    }));
    expect(result.summary).toEqual(expect.objectContaining({
      candidateCount: 1,
      attemptedCandidateCount: 1,
      plannedQueryCount: 1,
      fetchedQueryCount: 0,
      directHitCount: 0,
      acceptedDirectHits: [],
      stopReason: "completed",
    }));
    expect(result.candidates[0]).toEqual(expect.objectContaining({
      candidateId: "candidate-1",
      status: "planned",
      bodyClass: "not-fetched",
      recordCount: 0,
    }));
    expect(result).not.toHaveProperty("recommendations");
  });

  it("runs live candidates serially and stops on the first block", async () => {
    const searchMock = vi.fn()
      .mockResolvedValueOnce([searchHit()])
      .mockRejectedValueOnce(new RetryableVivinoBrowserError("search", "AWS WAF challenge"));
    vi.spyOn(VivinoBrowser, "getInstance").mockReturnValue({
      search: searchMock,
    } as unknown as VivinoBrowser);

    const result = await runProviderCanary({
      mode: "live",
      candidates: [
        candidate("candidate-1"),
        candidate("candidate-2"),
        candidate("candidate-3"),
      ],
    });

    expect(searchMock).toHaveBeenCalledTimes(2);
    const [firstCallOrder, secondCallOrder] = searchMock.mock.invocationCallOrder;
    expect(firstCallOrder).toBeDefined();
    expect(secondCallOrder).toBeDefined();
    expect(firstCallOrder as number).toBeLessThan(secondCallOrder as number);
    expect(result.summary).toEqual(expect.objectContaining({
      candidateCount: 3,
      attemptedCandidateCount: 2,
      fetchedQueryCount: 2,
      okCount: 1,
      blockedCount: 1,
      directHitCount: 1,
      stopReason: "blocked",
      acceptedDirectHits: [
        {
          candidateId: "candidate-1",
          matchScore: 0.8365714285714285,
          providerWineId: "123",
          matchedName: "Domaine Test Label",
        },
      ],
    }));
    expect(result.candidates.map((entry) => entry.candidateId)).toEqual(["candidate-1", "candidate-2"]);
    expect(result.candidates[1]).toEqual(expect.objectContaining({
      status: "blocked",
      bodyClass: "aws-waf-challenge",
    }));
  });

  it("uses cURL Explore transport when selected", async () => {
    appConfig.vivinoDirectSearchTransport = "curl-explore";
    const curlSearchMock = vi
      .spyOn(vivinoExploreCurl, "searchVivinoExploreWithCurl")
      .mockResolvedValue([searchHit()]);
    const browserSearchMock = vi.fn();
    vi.spyOn(VivinoBrowser, "getInstance").mockReturnValue({
      search: browserSearchMock,
    } as unknown as VivinoBrowser);

    const result = await runProviderCanary({
      mode: "live",
      candidates: [candidate("candidate-1")],
    });

    expect(curlSearchMock).toHaveBeenCalledTimes(1);
    expect(searchVivinoExploreWithCurl).toBeDefined();
    expect(browserSearchMock).not.toHaveBeenCalled();
    expect(result.summary).toEqual(expect.objectContaining({
      fetchedQueryCount: 1,
      okCount: 1,
      blockedCount: 0,
      directHitCount: 1,
      stopReason: "completed",
    }));
  });
});
