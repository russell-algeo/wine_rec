import { execFile } from "node:child_process";
import { promisify } from "node:util";

import { appConfig } from "../config.js";
import {
  pickPreferredVivinoImageUrl,
  RetryableVivinoBrowserError,
  type SearchHit,
} from "./vivino-browser.js";

const execFileAsync = promisify(execFile);

type VivinoExploreMatch = {
  vintage?: {
    id?: number | null;
    year?: number | string | null;
    statistics?: {
      ratings_average?: number | null;
      ratings_count?: number | null;
    } | null;
    image?: {
      location?: string | null;
      variations?: {
        large?: string | null;
        medium?: string | null;
        medium_square?: string | null;
        small_square?: string | null;
      } | null;
    } | null;
    wine?: {
      id?: number | null;
      name?: string | null;
      winery?: {
        name?: string | null;
      } | null;
      region?: {
        name?: string | null;
        country?: {
          name?: string | null;
        } | null;
      } | null;
    } | null;
  } | null;
  price?: {
    amount?: number | null;
  } | null;
};

type VivinoExploreResponse = {
  explore_vintage?: {
    records_matched?: number | null;
    matches?: VivinoExploreMatch[];
  } | null;
};

export type VivinoCurlBodyClass =
  | "ok"
  | "cloudfront-waf"
  | "aws-waf-challenge"
  | "rate-limited"
  | "parse-error"
  | "network-error"
  | "http-error";

export class RetryableVivinoCurlExploreError extends RetryableVivinoBrowserError {
  constructor(
    readonly query: string,
    readonly statusCode: number | null,
    readonly bodyClass: VivinoCurlBodyClass,
    reason: string,
  ) {
    super(`curl explore ${JSON.stringify(query)}`, `${bodyClass}: ${reason}`);
    this.name = "RetryableVivinoCurlExploreError";
  }
}

export function classifyVivinoCurlExploreBody(input: {
  statusCode: number | null;
  body?: string | null;
  errorMessage?: string | null;
}): VivinoCurlBodyClass {
  const haystack = [input.body, input.errorMessage].filter(Boolean).join("\n").toLowerCase();
  if (input.statusCode === 429 || /\brate limit|too many requests/.test(haystack)) return "rate-limited";
  if (input.statusCode === 403 && /cloudfront|request could not be satisfied|generated by cloudfront/.test(haystack)) {
    return "cloudfront-waf";
  }
  if (/aws.?waf|captcha|challenge/.test(haystack)) return "aws-waf-challenge";
  if (/network|econn|enotfound|timed out|timeout/.test(haystack)) return "network-error";
  if (input.statusCode !== null && input.statusCode >= 200 && input.statusCode < 300) return "ok";
  return "http-error";
}

function buildExploreUrl(query: string): URL {
  const url = new URL("https://www.vivino.com/api/explore/explore");
  for (const [name, value] of Object.entries({
    country_code: "US",
    currency_code: "USD",
    grape_filter: "varietal",
    min_rating: "1",
    order_by: "ratings_average",
    order: "desc",
    page: "1",
    per_page: "4",
    price_range_min: "0",
    price_range_max: "500",
    search_term: query,
  })) {
    url.searchParams.set(name, value);
  }
  return url;
}

function parseVintageYear(value: number | string | null | undefined): number | null {
  if (typeof value === "number" && Number.isFinite(value)) return value;
  if (typeof value === "string") {
    const parsed = Number.parseInt(value, 10);
    return Number.isFinite(parsed) ? parsed : null;
  }
  return null;
}

function matchToSearchHit(match: VivinoExploreMatch): SearchHit | null {
  const vintage = match.vintage;
  const wine = vintage?.wine;
  const wineId = wine?.id;
  if (wineId == null || !Number.isFinite(wineId)) return null;

  const wineryName = wine?.winery?.name?.trim() ?? "";
  const wineName = wine?.name?.trim() ?? "";
  if (!wineryName && !wineName) return null;

  const regionAndCountry = [
    wine?.region?.name?.trim(),
    wine?.region?.country?.name?.trim(),
  ].filter(Boolean).join(", ");

  return {
    wineId,
    wineryName,
    wineName,
    regionAndCountry,
    rating: vintage?.statistics?.ratings_average ?? null,
    retailPrice: match.price?.amount ?? null,
    imageUrl: pickPreferredVivinoImageUrl(
      vintage?.image?.variations?.large,
      vintage?.image?.variations?.medium,
      vintage?.image?.location,
      vintage?.image?.variations?.medium_square,
      vintage?.image?.variations?.small_square,
    ),
    vintagePageUrl: `https://www.vivino.com/w/${wineId}`,
    year: parseVintageYear(vintage?.year),
  };
}

export async function searchVivinoExploreWithCurl(query: string): Promise<SearchHit[]> {
  const marker = "\n__HTTP_STATUS__:";
  let stdout = "";
  let stderr = "";

  try {
    const result = await execFileAsync(
      "curl",
      [
        "-sS",
        "--compressed",
        "--max-time",
        "20",
        "-A",
        appConfig.vivinoDirectUserAgent,
        "-H",
        "Accept: application/json",
        "-H",
        "X-Requested-With: XMLHttpRequest",
        "-H",
        "Referer: https://www.vivino.com/en/explore",
        "-H",
        "Accept-Language: en-US,en;q=0.9",
        "-w",
        `${marker}%{http_code}`,
        buildExploreUrl(query).toString(),
      ],
      { maxBuffer: 12 * 1024 * 1024 },
    );
    stdout = result.stdout;
    stderr = result.stderr;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new RetryableVivinoCurlExploreError(query, null, "network-error", message);
  }

  const markerIndex = stdout.lastIndexOf(marker);
  const body = markerIndex >= 0 ? stdout.slice(0, markerIndex) : stdout;
  const statusCode = markerIndex >= 0 ? Number(stdout.slice(markerIndex + marker.length)) : null;
  const bodyClass = classifyVivinoCurlExploreBody({ statusCode, body, errorMessage: stderr });

  if (bodyClass !== "ok") {
    throw new RetryableVivinoCurlExploreError(
      query,
      statusCode,
      bodyClass,
      `HTTP ${statusCode ?? "unknown"}${stderr ? ` ${stderr}` : ""}`,
    );
  }

  let payload: VivinoExploreResponse;
  try {
    payload = JSON.parse(body) as VivinoExploreResponse;
  } catch (error) {
    throw new RetryableVivinoCurlExploreError(
      query,
      statusCode,
      "parse-error",
      error instanceof Error ? error.message : String(error),
    );
  }

  return (payload.explore_vintage?.matches ?? [])
    .map(matchToSearchHit)
    .filter((hit): hit is SearchHit => hit !== null);
}
